#!/usr/bin/env python3
"""Digest the sources the game is built from, so peers built from the same code agree.

    python scripts/source_identity.py [--root <repo>] [--write <SourceIdentity.cpp>]

The digest is SHA-256 over every C++ source under src/ and the VERSION file, keyed by
relative POSIX path, with CRLF read as LF so a Windows checkout and a Linux checkout of
the same commit agree. The online compatibility identity uses it in place of a hash of
the executable: another compiler, machine or operating system building the same sources
still matches. `--write` emits the translation unit defining gdl::game::sourceIdentity(),
rewritten only when the digest changes so an unchanged tree does not relink.
"""

import argparse
import hashlib
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
SOURCE_ROOT = "src"
SOURCE_SUFFIXES = (".h", ".hpp", ".inl", ".c", ".cpp")
EXTRA_FILES = ("VERSION",)


def source_files(root: pathlib.Path) -> list[str]:
    """Relative POSIX paths of every file the digest covers, in digest order."""
    files = [
        path.relative_to(root).as_posix()
        for path in (root / SOURCE_ROOT).rglob("*")
        if path.is_file() and path.suffix in SOURCE_SUFFIXES
    ]
    files.extend(name for name in EXTRA_FILES if (root / name).is_file())
    return sorted(files)


def digest(root: pathlib.Path) -> str:
    """SHA-256 over the covered files' paths and line-ending-normalised contents."""
    hasher = hashlib.sha256()
    for relative in source_files(root):
        content = (root / relative).read_bytes().replace(b"\r\n", b"\n")
        hasher.update(relative.encode("utf-8"))
        hasher.update(b"\0")
        hasher.update(len(content).to_bytes(8, "little"))
        hasher.update(content)
    return hasher.hexdigest()


def unit(value: str) -> str:
    """The C++ translation unit that reports a digest."""
    return (
        "// Generated by scripts/source_identity.py at build time; do not edit.\n"
        '#include "game/app/SourceIdentity.h"\n'
        "\n"
        "namespace gdl::game {\n"
        "\n"
        "std::string_view sourceIdentity() {\n"
        f'    return "{value}";\n'
        "}\n"
        "\n"
        "} // namespace gdl::game\n"
    )


def write(path: pathlib.Path, text: str) -> bool:
    """Writes the file only when its content would change; returns whether it did."""
    data = text.encode("utf-8")
    if path.is_file() and path.read_bytes() == data:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(data)
    return True


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--root", type=pathlib.Path, default=ROOT,
                        help="the repository to digest (default: this checkout)")
    parser.add_argument("--write", type=pathlib.Path,
                        help="emit the translation unit here when the digest changed")
    args = parser.parse_args(argv)
    value = digest(args.root.resolve())
    if args.write:
        write(args.write, unit(value))
    print(value)
    return 0


if __name__ == "__main__":
    sys.exit(main())
